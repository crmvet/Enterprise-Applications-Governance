namespace Product.Azure.Stores.SqlServer;

// Writes the Azure SQL scripts that follow from the logical model: sql/0001-tables.sql (a table per first-release
// entity), sql/0002-security.sql (row-level security on SESSION_CONTEXT), sql/0003-app-user.sql (the app's database
// user and its least-privilege role) and sql/0008-data-taxonomy.sql (the data taxonomy's tables, the subject check on
// Owner Assignment, and the security policy again over every table). The text is deterministic: the checked-in files
// must equal it (the drift test), and the local server's schema-script command writes it. sql/0004-host.sql to
// sql/0007-record-numbers.sql are written by hand.
public static class SqlServerSchemaScript
{
    public const string TablesFile = "0001-tables.sql";
    public const string SecurityFile = "0002-security.sql";

    /// <summary>The one row-level security policy of 0002: every filter and block predicate on every product table.</summary>
    public const string PolicyName = "ProductPolicy";
    public const string AppUserFile = "0003-app-user.sql";

    // The data taxonomy (D-37, settled by D-41; document 22, B22-14).
    public const string DataTaxonomyFile = "0008-data-taxonomy.sql";

    // The migration that creates each table the first release did not have. A deployed database never runs a script it
    // has recorded again (SqlServerMigrations), so 0001 keeps the tables it had when the first database was deployed, and
    // a table the model adds later is created by the numbered script of its own. An entity not listed here is in 0001.
    public static readonly IReadOnlyDictionary<string, int> LaterTables = new System.Collections.ObjectModel.ReadOnlyDictionary<string, int>(new Dictionary<string, int>(StringComparer.Ordinal)
    {
        ["C47"] = 8,
        ["C48"] = 8,
        ["C49"] = 8,
        ["C50"] = 8,
        ["O25"] = 8,
        ["O26"] = 8,
        ["O27"] = 8,
    });

    // The database role of the app's managed identity, and the role whose members may seed and migrate.
    public const string AppRole = "product_app";
    public const string MigratorRole = "product_migrator";

    private static readonly string[] Schemas = { "config", "ops", "audit", "security", "host" };

    // The deployment identity: the database owner (the Entra administrator maps to dbo, principal ID 1) or a member of
    // the migrator role. IS_ROLEMEMBER answers 0 for dbo, so both tests are needed.
    private static readonly string Migrator = "(DATABASE_PRINCIPAL_ID() = 1 OR IS_ROLEMEMBER(N'" + MigratorRole + "') = 1)";

    // Every generated script, by file name.
    public static IReadOnlyList<KeyValuePair<string, string>> GenerateAll(EntityCatalog catalog)
    {
        return new[]
        {
            new KeyValuePair<string, string>(TablesFile, GenerateTables(catalog)),
            new KeyValuePair<string, string>(SecurityFile, GenerateSecurity(catalog)),
            new KeyValuePair<string, string>(AppUserFile, GenerateAppUser(catalog)),
            new KeyValuePair<string, string>(DataTaxonomyFile, GenerateDataTaxonomy(catalog)),
        };
    }

    // The migration that creates the entity's table: 1, or the number LaterTables gives.
    public static int TableMigration(EntityInfo entity)
    {
        if (entity == null)
        {
            throw new ArgumentNullException(nameof(entity));
        }

        return LaterTables.TryGetValue(entity.ModelId, out int migration) ? migration : 1;
    }

    // The entities whose tables one migration creates.
    public static IReadOnlyList<EntityInfo> TablesOf(EntityCatalog catalog, int migration)
    {
        if (catalog == null)
        {
            throw new ArgumentNullException(nameof(catalog));
        }

        return catalog.Entities.Where(e => TableMigration(e) == migration).ToList();
    }

    // ---- 0001: tables ----

    public static string GenerateTables(EntityCatalog catalog)
    {
        if (catalog == null)
        {
            throw new ArgumentNullException(nameof(catalog));
        }

        IReadOnlyList<EntityInfo> entities = TablesOf(catalog, 1);
        int temporal = entities.Count(e => e.Storage == EntityStorage.Temporal);
        int updatable = entities.Count(e => e.Storage == EntityStorage.UpdatableLedger);
        int appendOnly = entities.Count(e => e.Storage == EntityStorage.AppendOnlyLedger);
        var w = new Writer();
        w.Line("-- Azure SQL migration 0001: one table per entity of the first release.");
        w.Line("-- Generated by SqlServerSchemaScript.GenerateTables from the logical model compiled into the engine core (model " + catalog.ModelVersion + ").");
        w.Line("-- Do not edit by hand: run the local server's schema-script command, or the store tests with PRODUCT_WRITE_SQL=1.");
        w.Line("--");
        w.Line("-- Every table holds the engine's rows in the shape of its storage ports: the row ID, the configuration key path (null");
        w.Line("-- for operational rows), the row's columns as canonical JSON in logical names, and an optimistic version. Beside them");
        w.Line("-- are the performer of the last write and the promoted columns that the unique keys, the version probe and the");
        w.Line("-- row-level security block predicates read, copied from the JSON by the store in the same statement.");
        w.Line("-- History (document 22, sections 2.3 and 11.2): " + temporal + " system-versioned temporal tables, " + updatable + " updatable ledger tables");
        w.Line("-- (" + string.Join(", ", entities.Where(e => e.Storage == EntityStorage.UpdatableLedger).Select(e => e.ModelId)) + ") and " + appendOnly
            + " append-only ledger tables (" + string.Join(", ", entities.Where(e => e.Storage == EntityStorage.AppendOnlyLedger).Select(e => e.ModelId)) + ").");
        w.Line("-- Every statement checks before it acts, so the script can run again after a stop part way.");
        w.Line();
        foreach (string schema in Schemas)
        {
            w.Line("IF SCHEMA_ID(N'" + schema + "') IS NULL EXEC (N'CREATE SCHEMA [" + schema + "]');");
        }

        w.Go();
        Tables(w, entities);
        return w.ToString();
    }

    // CREATE TABLE and the indexes of each entity, in the shape of the storage ports (see 0001's header).
    private static void Tables(Writer w, IEnumerable<EntityInfo> entities)
    {
        foreach (EntityInfo e in entities)
        {
            w.Line("-- " + e.ModelId + " " + e.LogicalName + " (" + e.Key + "): history class " + e.HistoryClass + ", " + StorageText(e.Storage) + ". Delete policy: " + e.DeletePolicy + ".");
            w.Line("IF OBJECT_ID(N'" + e.QualifiedTable + "', N'U') IS NULL");
            w.Line("BEGIN");
            w.Line("    CREATE TABLE " + e.QualifiedTable);
            w.Line("    (");
            var items = new List<string>
            {
                "[Id] varchar(" + RowStore.MaxIdLength + ") COLLATE Latin1_General_BIN2 NOT NULL",
                "[Key] nvarchar(" + RowStore.MaxKeyLength + ") COLLATE Latin1_General_BIN2 NULL",
                "[Columns] nvarchar(max) NOT NULL",
                "[Version] bigint NOT NULL",
            };
            items.AddRange(e.Promoted.Select(p => "[" + p.SqlName + "] " + p.SqlType + " NULL"));
            items.Add("[CreatedOn] datetime2(3) NOT NULL CONSTRAINT [DF_" + e.Table + "_CreatedOn] DEFAULT (SYSUTCDATETIME())");
            items.Add("[ModifiedOn] datetime2(3) NOT NULL CONSTRAINT [DF_" + e.Table + "_ModifiedOn] DEFAULT (SYSUTCDATETIME())");
            if (e.Storage == EntityStorage.Temporal)
            {
                items.Add("[ValidFrom] datetime2(7) GENERATED ALWAYS AS ROW START HIDDEN NOT NULL");
                items.Add("[ValidTo] datetime2(7) GENERATED ALWAYS AS ROW END HIDDEN NOT NULL");
                items.Add("PERIOD FOR SYSTEM_TIME ([ValidFrom], [ValidTo])");
            }

            items.Add("CONSTRAINT [PK_" + e.Table + "] PRIMARY KEY CLUSTERED ([Id])");
            items.Add("CONSTRAINT [CK_" + e.Table + "_Columns] CHECK (ISJSON([Columns]) = 1)");
            for (int i = 0; i < items.Count; i++)
            {
                w.Line("        " + items[i] + (i < items.Count - 1 ? "," : string.Empty));
            }

            w.Line("    )");
            switch (e.Storage)
            {
                case EntityStorage.Temporal:
                    w.Line("    WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = " + e.QualifiedHistoryTable + "));");
                    break;
                case EntityStorage.UpdatableLedger:
                    w.Line("    WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = " + e.QualifiedHistoryTable + "), LEDGER = ON);");
                    break;
                default:
                    w.Line("    WITH (LEDGER = ON (APPEND_ONLY = ON));");
                    break;
            }

            w.Line("END;");
            w.Go();

            Index(w, e, "IX_" + e.Table + "_Key", unique: false, new[] { "Key" });
            foreach (IGrouping<string?, PromotedColumn> group in e.Promoted.Where(p => p.IsUnique).GroupBy(p => p.UniqueGroup))
            {
                Index(w, e, "UX_" + e.Table + "_" + group.Key, unique: true, group.Select(p => p.SqlName).ToArray());
            }

            foreach (PromotedColumn column in e.Promoted.Where(p => p.Indexed))
            {
                Index(w, e, "IX_" + e.Table + "_" + column.SqlName, unique: false, new[] { column.SqlName });
            }

            w.Go();
        }
    }

    // ---- 0002: row-level security ----

    public static string GenerateSecurity(EntityCatalog catalog)
    {
        if (catalog == null)
        {
            throw new ArgumentNullException(nameof(catalog));
        }

        // The final meanings come from the engine's contract lists and guard (G-05, G-06, G-16), never a copy here.
        string[] decisionFinal = EngineContract.DecisionStatusMeanings.WireValues
            .Where(v => EngineContract.DecisionStatusMeanings.TryParse(v, out DecisionStatusMeaning m) && ContractFacts.IsFinal(m))
            .ToArray();
        string pending = EngineContract.ApprovalOutcomeMeanings.ToWire(ApprovalOutcomeMeaning.Pending);
        string[] runnerOutcomes =
        {
            EngineContract.ApprovalOutcomeMeanings.ToWire(ApprovalOutcomeMeaning.Approved),
            EngineContract.ApprovalOutcomeMeanings.ToWire(ApprovalOutcomeMeaning.Rejected),
            EngineContract.ApprovalOutcomeMeanings.ToWire(ApprovalOutcomeMeaning.RecommendationOnly),
        };
        string[] draftOpen =
        {
            EngineContract.DraftStatusMeanings.ToWire(DraftStatusMeaning.Draft),
            EngineContract.DraftStatusMeanings.ToWire(DraftStatusMeaning.Submitted),
        };
        string runner = EngineContract.ActorKindMeanings.ToWire(ActorKindMeaning.ApprovalRunner);
        string personKind = EngineContract.ActorKindMeanings.ToWire(ActorKindMeaning.Person);
        string engineKind = EngineContract.ActorKindMeanings.ToWire(ActorKindMeaning.Engine);
        string actorKind = "CAST(SESSION_CONTEXT(N'ActorKind') AS nvarchar(64))";
        string operation = "CAST(SESSION_CONTEXT(N'EngineOperation') AS nvarchar(32))";
        string answered = "CAST(SESSION_CONTEXT(N'AnsweredApprovalId') AS varchar(36))";

        // A person answering their own Approval Record through answer_approval on the person entry (D-38): the host names
        // the record in AnsweredApprovalId for that request only.
        string personAnswer = "(" + actorKind + " = N'" + personKind + "' AND CAST(SESSION_CONTEXT(N'Entry') AS nvarchar(16)) = N'"
            + SqlServerRowDatabase.EntryWire(CallerEntry.Person) + "' AND " + answered + " IS NOT NULL)";

        // The request reaches only the records of the answered record's own decision: the answer itself and the recompute
        // the engine runs on that decision. AnsweredApprovalId comes from the caller's argument before the engine checks
        // it, so the predicate never trusts it beyond that one decision. The decision is read from the row's JSON, as the
        // store writes it, so no column is added to a table that already holds rows.
        string approvalTable = catalog.Entities.First(e => e.Key == "approval-record").QualifiedTable;
        string sameDecision = "EXISTS (SELECT 1 FROM " + approvalTable + " AS [answered] WHERE [answered].[Id] = " + answered
            + " AND JSON_VALUE([answered].[Columns], N'$.decision') = JSON_VALUE(@Columns, N'$.decision'))";

        // A write in that request is the caller's own: the engine stamps the caller's principal on the answer and on every
        // nested recompute write (WriteGuard, Stamps), so a row stamped with anyone else is not the engine's.
        string byCaller = "LOWER(@PerformedByPrincipalId) = LOWER(CAST(SESSION_CONTEXT(N'PrincipalId') AS nvarchar(64)))";

        var w = new Writer();
        w.Line("-- Azure SQL migration 0002: row-level security on SESSION_CONTEXT (document 22, sections 11.1 and 11.3).");
        w.Line("-- Generated by SqlServerSchemaScript.GenerateSecurity from the logical model and the engine's contract lists.");
        w.Line("-- Do not edit by hand: run the local server's schema-script command, or the store tests with PRODUCT_WRITE_SQL=1.");
        w.Line("--");
        w.Line("-- The store sets the caller in SESSION_CONTEXT, read-only, on every connection it opens: PrincipalId, Entry, ActorKind,");
        w.Line("-- OnBehalfOfId, ClientApp, ClientAppVerified, Roles, CorrelationId, EngineOperation (read, write, activation or");
        w.Line("-- seed) and, for a person's answer through answer_approval (D-38), AnsweredApprovalId. The filter predicate hides every");
        w.Line("-- product row from a connection without a caller, except for the deployment identity. The block predicates are a");
        w.Line("-- backstop behind the engine's guard: they refuse what the engine never writes.");
        w.Line("--   fn_ConfigWriter: live configuration rows change only inside an activation (or a seed by the deployment identity).");
        w.Line("--   fn_DraftOpen: a Configuration Draft changes only while " + string.Join(" or ", draftOpen) + ".");
        w.Line("--   fn_DecisionOpen: a final Decision (" + string.Join(", ", decisionFinal) + ") changes once more only to set Superseded By.");
        w.Line("--   fn_ApprovalPending: an Approval Record changes only while " + pending + ", or in the approval runner's request, or in a");
        w.Line("--     person's own answer request (D-38) on a record of the answered record's decision, where the engine's recompute");
        w.Line("--     rewrites what counts. Final records of every other decision stay locked in that request.");
        w.Line("--   fn_ApprovalOutcomeWriter: only the approval runner writes " + string.Join(", ", runnerOutcomes) + ", or, in a person's own");
        w.Line("--     answer request, a write stamped with that person on a record of the answered record's decision: the answer on");
        w.Line("--     the record the request names, and the engine's recompute on records already answered.");
        w.Line("--   fn_AssessmentOpen and fn_GapRunOpen: a Tier Assessment with a Tier Decision and a finished Gap Check Run are final.");
        w.Line("-- Read scoping by role (intake, claim, portfolio and audit readers) stays in the tool outputs in this release: the engine");
        w.Line("-- reads every fact it evaluates. Ledger history tables get no predicate; 0003 denies the app every history table and");
        w.Line("-- ledger view instead. One security policy holds every filter and block predicate: Azure SQL lets only one enabled");
        w.Line("-- policy reference a table (error 33264). It is dropped first so the functions can change, then created again; the");
        w.Line("-- two policy names of earlier drafts of this script are dropped too.");
        w.Line();
        w.Line("IF OBJECT_ID(N'[security].[" + PolicyName + "]', N'SP') IS NOT NULL DROP SECURITY POLICY [security].[" + PolicyName + "];");
        w.Line("IF OBJECT_ID(N'[security].[ProductWritePolicy]', N'SP') IS NOT NULL DROP SECURITY POLICY [security].[ProductWritePolicy];");
        w.Line("IF OBJECT_ID(N'[security].[ProductReadPolicy]', N'SP') IS NOT NULL DROP SECURITY POLICY [security].[ProductReadPolicy];");
        w.Go();

        Function(w, "fn_HasCaller", "@Id varchar(36)",
            "SESSION_CONTEXT(N'PrincipalId') IS NOT NULL",
            "DATABASE_PRINCIPAL_ID() = 1",
            "IS_ROLEMEMBER(N'" + MigratorRole + "') = 1");
        Function(w, "fn_ConfigWriter", "@Id varchar(36)",
            operation + " = N'" + RowStoreOperations.Activation + "'",
            "(" + operation + " = N'" + RowStoreOperations.Seed + "' AND " + Migrator + ")");
        Function(w, "fn_DraftOpen", "@DraftStatus nvarchar(32)",
            "@DraftStatus IS NULL",
            "@DraftStatus IN (" + List(draftOpen) + ")",
            Migrator);
        Function(w, "fn_DecisionOpen", "@StatusMeaning nvarchar(32), @SupersededById nvarchar(64)",
            "@StatusMeaning IS NULL",
            "@StatusMeaning NOT IN (" + List(decisionFinal) + ")",
            "@SupersededById IS NULL",
            Migrator);
        Function(w, "fn_ApprovalPending", "@OutcomeMeaning nvarchar(32), @Columns nvarchar(max)",
            "@OutcomeMeaning IS NULL",
            "@OutcomeMeaning = N'" + pending + "'",
            actorKind + " = N'" + runner + "'",
            "(" + personAnswer + " AND " + sameDecision + ")",
            Migrator);
        Function(w, "fn_ApprovalOutcomeWriter", "@OutcomeMeaning nvarchar(32), @Id varchar(36), @PerformedByActorKind nvarchar(32), @PerformedByPrincipalId nvarchar(64), @Columns nvarchar(max)",
            "@OutcomeMeaning IS NULL",
            "@OutcomeMeaning NOT IN (" + List(runnerOutcomes) + ")",
            actorKind + " = N'" + runner + "'",
            "(" + personAnswer + " AND (@Id = " + answered + " OR @PerformedByActorKind = N'" + engineKind + "') AND " + byCaller + " AND " + sameDecision + ")",
            Migrator);
        Function(w, "fn_AssessmentOpen", "@TierDecisionId nvarchar(64)",
            "@TierDecisionId IS NULL",
            Migrator);
        Function(w, "fn_GapRunOpen", "@FinishedOn nvarchar(40)",
            "@FinishedOn IS NULL",
            Migrator);

        Policy(w, PolicyName, PolicyPredicates(TablesOf(catalog, 1)));
        return w.ToString();
    }

    // Every filter and block predicate of the one security policy on the given tables: the filters first, then the
    // blocks, both in table order. The filters and the blocks go into one policy (see 0002's header): two enabled
    // policies on one table are refused.
    private static List<string> PolicyPredicates(IEnumerable<EntityInfo> entities)
    {
        EntityInfo[] tables = entities.ToArray();
        var filters = new List<string>();
        foreach (EntityInfo e in tables)
        {
            filters.Add("ADD FILTER PREDICATE [security].[fn_HasCaller]([Id]) ON " + e.QualifiedTable);
            if (e.Storage == EntityStorage.Temporal)
            {
                filters.Add("ADD FILTER PREDICATE [security].[fn_HasCaller]([Id]) ON " + e.QualifiedHistoryTable);
            }
        }

        var blocks = new List<string>();
        foreach (EntityInfo e in tables)
        {
            if (e.IsConfiguration && e.Key != "configuration-draft")
            {
                blocks.Add("ADD BLOCK PREDICATE [security].[fn_ConfigWriter]([Id]) ON " + e.QualifiedTable + " AFTER INSERT");
                if (e.Storage != EntityStorage.AppendOnlyLedger)
                {
                    blocks.Add("ADD BLOCK PREDICATE [security].[fn_ConfigWriter]([Id]) ON " + e.QualifiedTable + " AFTER UPDATE");
                    blocks.Add("ADD BLOCK PREDICATE [security].[fn_ConfigWriter]([Id]) ON " + e.QualifiedTable + " BEFORE DELETE");
                }
            }

            switch (e.Key)
            {
                case "configuration-draft":
                    blocks.Add("ADD BLOCK PREDICATE [security].[fn_DraftOpen]([DraftStatus]) ON " + e.QualifiedTable + " BEFORE UPDATE");
                    break;
                case "decision":
                    blocks.Add("ADD BLOCK PREDICATE [security].[fn_DecisionOpen]([StatusMeaning], [SupersededById]) ON " + e.QualifiedTable + " BEFORE UPDATE");
                    break;
                case "approval-record":
                    blocks.Add("ADD BLOCK PREDICATE [security].[fn_ApprovalPending]([OutcomeMeaning], [Columns]) ON " + e.QualifiedTable + " BEFORE UPDATE");
                    blocks.Add("ADD BLOCK PREDICATE [security].[fn_ApprovalOutcomeWriter]([OutcomeMeaning], [Id], [PerformedByActorKind], [PerformedByPrincipalId], [Columns]) ON " + e.QualifiedTable + " AFTER INSERT");
                    blocks.Add("ADD BLOCK PREDICATE [security].[fn_ApprovalOutcomeWriter]([OutcomeMeaning], [Id], [PerformedByActorKind], [PerformedByPrincipalId], [Columns]) ON " + e.QualifiedTable + " AFTER UPDATE");
                    break;
                case "tier-assessment":
                    blocks.Add("ADD BLOCK PREDICATE [security].[fn_AssessmentOpen]([TierDecisionId]) ON " + e.QualifiedTable + " BEFORE UPDATE");
                    break;
                case "gap-check-run":
                    blocks.Add("ADD BLOCK PREDICATE [security].[fn_GapRunOpen]([FinishedOn]) ON " + e.QualifiedTable + " BEFORE UPDATE");
                    break;
            }
        }

        return filters.Concat(blocks).ToList();
    }

    // ---- 0003: the app's database user ----

    public static string GenerateAppUser(EntityCatalog catalog)
    {
        if (catalog == null)
        {
            throw new ArgumentNullException(nameof(catalog));
        }

        string[] neverDeleted = TablesOf(catalog, 1)
            .Where(e => e.Schema == "ops" && e.DeletePolicy == "never")
            .Select(e => e.QualifiedTable)
            .ToArray();

        var w = new Writer();
        w.Line("-- Azure SQL migration 0003: the app's database user and its least-privilege role (document 22, section 11.1).");
        w.Line("-- Generated by SqlServerSchemaScript.GenerateAppUser from the logical model's delete policies.");
        w.Line("-- Do not edit by hand: run the local server's schema-script command, or the store tests with PRODUCT_WRITE_SQL=1.");
        w.Line("--");
        w.Line("-- Variable $(AppIdentityName): the name of the app's user-assigned managed identity, as Microsoft Entra ID shows it.");
        w.Line("-- Empty skips the user (a test server without Microsoft Entra ID). Run by the deployment identity, which is the database");
        w.Line("-- owner; another deployment identity is added to " + MigratorRole + " (and given its DDL rights) by a person.");
        w.Line("--");
        w.Line("-- " + AppRole + ": reads and writes the engine's rows and nothing else. No DDL. No delete in config or audit, and none on the");
        w.Line("-- operational tables whose rows are never deleted (document 22, section 2.5); the engine decides which drafts go.");
        w.Line("-- No read of history tables or ledger views: the engine reads current rows only, and auditors read history elsewhere.");
        w.Line("-- The approval outcome columns are written only in the approval runner's request or in a person's own answer request");
        w.Line("-- (0002, D-38). The separate approval_writer principal of document 22 needs a second identity and connection and is");
        w.Line("-- not in this release.");
        w.Line();
        w.Line("IF DATABASE_PRINCIPAL_ID(N'" + AppRole + "') IS NULL CREATE ROLE [" + AppRole + "];");
        w.Line("IF DATABASE_PRINCIPAL_ID(N'" + MigratorRole + "') IS NULL CREATE ROLE [" + MigratorRole + "];");
        w.Go();
        w.Line("GRANT SELECT, INSERT, UPDATE ON SCHEMA::[config] TO [" + AppRole + "];");
        w.Line("GRANT SELECT, INSERT, UPDATE, DELETE ON SCHEMA::[ops] TO [" + AppRole + "];");
        w.Line("GRANT SELECT, INSERT ON SCHEMA::[audit] TO [" + AppRole + "];");
        foreach (string table in neverDeleted)
        {
            w.Line("DENY DELETE ON " + table + " TO [" + AppRole + "];");
        }

        foreach (string schema in Schemas)
        {
            w.Line("DENY ALTER ON SCHEMA::[" + schema + "] TO [" + AppRole + "];");
        }

        w.Go();
        DenyHistoryReads(w);
        w.Line("IF N'$(AppIdentityName)' <> N'' AND DATABASE_PRINCIPAL_ID(N'$(AppIdentityName)') IS NULL");
        w.Line("    EXEC (N'CREATE USER [$(AppIdentityName)] FROM EXTERNAL PROVIDER');");
        w.Line("IF N'$(AppIdentityName)' <> N'' AND NOT EXISTS (");
        w.Line("    SELECT 1 FROM sys.database_role_members AS m");
        w.Line("    WHERE m.[role_principal_id] = DATABASE_PRINCIPAL_ID(N'" + AppRole + "') AND m.[member_principal_id] = DATABASE_PRINCIPAL_ID(N'$(AppIdentityName)'))");
        w.Line("    EXEC (N'ALTER ROLE [" + AppRole + "] ADD MEMBER [$(AppIdentityName)]');");
        w.Go();
        return w.ToString();
    }

    // The app may not read a history table or a ledger view. The names are read from the catalog views when the script
    // runs, so the block denies every one that exists then, and a later script runs it again for the tables it adds.
    private static void DenyHistoryReads(Writer w)
    {
        w.Line("DECLARE @deny nvarchar(max);");
        w.Line("SELECT @deny = STRING_AGG(CAST(N'DENY SELECT ON ' + QUOTENAME(s.[name]) + N'.' + QUOTENAME(o.[name]) + N' TO [" + AppRole + "];' AS nvarchar(max)), NCHAR(10))");
        w.Line("FROM");
        w.Line("(");
        w.Line("    SELECT h.[schema_id], h.[name] FROM sys.tables AS t JOIN sys.tables AS h ON h.[object_id] = t.[history_table_id]");
        w.Line("    WHERE SCHEMA_NAME(t.[schema_id]) IN (N'config', N'ops', N'audit')");
        w.Line("    UNION ALL");
        w.Line("    SELECT v.[schema_id], v.[name] FROM sys.tables AS t JOIN sys.views AS v ON v.[object_id] = t.[ledger_view_id]");
        w.Line("    WHERE SCHEMA_NAME(t.[schema_id]) IN (N'config', N'ops', N'audit')");
        w.Line(") AS o");
        w.Line("JOIN sys.schemas AS s ON s.[schema_id] = o.[schema_id];");
        w.Line("IF @deny IS NOT NULL EXEC sys.sp_executesql @deny;");
        w.Go();
    }

    // ---- 0008: the data taxonomy ----

    // The data taxonomy (D-37, settled by D-41; document 22, B22-14): the tables of C47 to C50 and O25 to O27, the check
    // that an Owner Assignment names exactly one subject, the one security policy again over every table, and the app's
    // history reads denied on the new history tables. The functions of 0002 do not change, so they are not written again.
    public static string GenerateDataTaxonomy(EntityCatalog catalog)
    {
        if (catalog == null)
        {
            throw new ArgumentNullException(nameof(catalog));
        }

        IReadOnlyList<EntityInfo> entities = TablesOf(catalog, 8);
        EntityInfo[] checkedTables = catalog.Entities.Where(e => e.SubjectCheck != null).ToArray();
        var w = new Writer();
        w.Line("-- Azure SQL migration 0008: the data taxonomy (D-37, settled by D-41; document 22, B22-14).");
        w.Line("-- Generated by SqlServerSchemaScript.GenerateDataTaxonomy from the logical model compiled into the engine core (model " + catalog.ModelVersion + ").");
        w.Line("-- Do not edit by hand: run the local server's schema-script command, or the store tests with PRODUCT_WRITE_SQL=1.");
        w.Line("--");
        w.Line("-- A deployed database has run 0001 to 0007 and never runs them again, so this script adds what the data taxonomy needs:");
        w.Line("--   1. A table for each data taxonomy entity (" + string.Join(", ", entities.Select(e => e.ModelId)) + "), in the shape of 0001:");
        w.Line("--      system-versioned temporal tables with a history table, like the other class E and V tables.");
        w.Line("--   2. The subject check of " + string.Join(", ", checkedTables.Select(e => e.ModelId + " " + e.LogicalName)) + " (document 22, section 2.6): exactly one subject column");
        w.Line("--      holds a value, and Subject Kind names it. An empty Subject Kind means the first subject, so every row written");
        w.Line("--      before the data taxonomy, which names its application only, passes. The check reads the row's JSON as the store");
        w.Line("--      writes it, and the store makes the same check before a write reaches the database (EntityInfo.SubjectCheck).");
        w.Line("--      O09 Decision's subjects stay the engine's to check: its tools also write Subject Application beside a subject of");
        w.Line("--      another kind, and its frozen ledger rows could never be corrected.");
        w.Line("--   3. The one security policy of 0002, dropped before the subject check changes a table it covers and created again");
        w.Line("--      over every table, the new ones included, because a schema-bound policy names each table it covers. The");
        w.Line("--      predicate functions of 0002 are unchanged.");
        w.Line("--   4. The app's reads of the new history tables denied, as 0003 does for the others. The schema grants of 0003 cover");
        w.Line("--      the new tables; none of them is in the list the app may never delete from.");
        w.Line("-- Every statement checks before it acts, so the script can run again after a stop part way.");
        w.Line();
        Tables(w, entities);

        // The policy is schema-bound to every table it names, so it goes before the constraint changes a table it covers,
        // and comes back over every table once they are done.
        w.Line("IF OBJECT_ID(N'[security].[" + PolicyName + "]', N'SP') IS NOT NULL DROP SECURITY POLICY [security].[" + PolicyName + "];");
        w.Go();
        foreach (EntityInfo e in checkedTables)
        {
            SubjectCheck check = e.SubjectCheck!;
            string name = "CK_" + e.Table + "_" + check.Name;
            w.Line("IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE [name] = N'" + name + "' AND [parent_object_id] = OBJECT_ID(N'" + e.QualifiedTable + "'))");
            w.Line("    ALTER TABLE " + e.QualifiedTable + " WITH CHECK ADD CONSTRAINT [" + name + "] CHECK");
            w.Line("    (");
            w.Line("        " + string.Join("\n        + ", check.Subjects.Select(s => "CASE WHEN " + Member(s.Value) + " IS NULL THEN 0 ELSE 1 END")) + " = 1");
            w.Line("        AND");
            w.Line("        (");
            w.Line("            (" + Member(check.KindColumn) + " IS NULL AND " + Member(check.Subjects[0].Value) + " IS NOT NULL)");
            foreach (KeyValuePair<string, string> subject in check.Subjects)
            {
                w.Line("            OR (" + Member(check.KindColumn) + " = N'" + subject.Key + "' AND " + Member(subject.Value) + " IS NOT NULL)");
            }

            w.Line("        )");
            w.Line("    );");
            w.Go();
        }

        Policy(w, PolicyName, PolicyPredicates(catalog.Entities));
        DenyHistoryReads(w);
        return w.ToString();
    }

    // A member of the row's JSON as the subject check reads it: its scalar value, ordinal, with the empty string as null.
    private static string Member(string jsonName)
    {
        return "NULLIF(JSON_VALUE([Columns], N'$." + jsonName + "'), N'') COLLATE Latin1_General_BIN2";
    }

    private static string StorageText(EntityStorage storage)
    {
        switch (storage)
        {
            case EntityStorage.Temporal:
                return "system-versioned temporal table";
            case EntityStorage.UpdatableLedger:
                return "updatable ledger table";
            default:
                return "append-only ledger table";
        }
    }

    private static void Index(Writer w, EntityInfo e, string name, bool unique, string[] columns)
    {
        w.Line("IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE [object_id] = OBJECT_ID(N'" + e.QualifiedTable + "') AND [name] = N'" + name + "')");
        string filter = unique ? " WHERE " + string.Join(" AND ", columns.Select(c => "[" + c + "] IS NOT NULL")) : string.Empty;
        w.Line("    CREATE " + (unique ? "UNIQUE " : string.Empty) + "INDEX [" + name + "] ON " + e.QualifiedTable + " (" + string.Join(", ", columns.Select(c => "[" + c + "]")) + ")" + filter + ";");
    }

    private static void Function(Writer w, string name, string parameters, params string[] allowedWhen)
    {
        w.Line("CREATE OR ALTER FUNCTION [security].[" + name + "] (" + parameters + ")");
        w.Line("RETURNS TABLE");
        w.Line("WITH SCHEMABINDING");
        w.Line("AS");
        w.Line("RETURN SELECT 1 AS [Allowed]");
        for (int i = 0; i < allowedWhen.Length; i++)
        {
            w.Line((i == 0 ? "    WHERE " : "       OR ") + allowedWhen[i] + (i == allowedWhen.Length - 1 ? ";" : string.Empty));
        }

        w.Go();
    }

    private static void Policy(Writer w, string name, IReadOnlyList<string> predicates)
    {
        w.Line("CREATE SECURITY POLICY [security].[" + name + "]");
        for (int i = 0; i < predicates.Count; i++)
        {
            w.Line("    " + predicates[i] + (i < predicates.Count - 1 ? "," : string.Empty));
        }

        w.Line("WITH (STATE = ON, SCHEMABINDING = ON);");
        w.Go();
    }

    private static string List(IEnumerable<string> values)
    {
        return string.Join(", ", values.Select(v => "N'" + v + "'"));
    }

    // Text with "\n" line ends, whatever the platform.
    private sealed class Writer
    {
        private readonly StringBuilder _text = new();

        public void Line(string line = "")
        {
            _text.Append(line).Append('\n');
        }

        public void Go()
        {
            _text.Append("GO\n\n");
        }

        public override string ToString()
        {
            return _text.ToString().TrimEnd('\n') + "\n";
        }
    }
